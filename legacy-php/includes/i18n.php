/**
 * Lightweight translations for public/admin chrome plus translated content fallbacks.
 * Database content uses *_tr and *_de columns when editorial translation is available.
 */

function vdj_supported_languages(): array {
    return [
        'en' => ['label' => 'English', 'short' => 'EN', 'flag' => '🇬🇧'],
        'tr' => ['label' => 'Türkçe',  'short' => 'TR', 'flag' => '🇹🇷'],
        'de' => ['label' => 'Deutsch', 'short' => 'DE', 'flag' => '🇩🇪'],
    ];
}

function vdj_bootstrap_language(): string {
    session_start_if_not_started();
    $supported = vdj_supported_languages();
    $path = parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH) ?: '/';
    $firstSegment = strtolower(explode('/', trim($path, '/'))[0] ?? '');
    if (in_array($firstSegment, ['tr', 'de'], true)) {
        $lang = $firstSegment;
    } elseif (str_starts_with($path, '/admin')) {
        $lang = $_GET['lang'] ?? ($_SESSION['vdj_lang'] ?? ($_COOKIE['vdj_lang'] ?? 'en'));
    } else {
        $lang = $_GET['lang'] ?? 'en';
    }
    $lang = is_string($lang) ? strtolower(substr($lang, 0, 2)) : 'en';
    if (!isset($supported[$lang])) $lang = 'en';

    $_SESSION['vdj_lang'] = $lang;
    if (!headers_sent()) {
        setcookie('vdj_lang', $lang, [
            'expires' => time() + 31536000,
            'path' => '/',
            'secure' => !empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off',
            'httponly' => false,
            'samesite' => 'Lax',
        ]);
    }
    return $lang;
}

function vdj_current_language(): string {
    static $lang = null;
    if ($lang === null) $lang = vdj_bootstrap_language();
    return $lang;
}

