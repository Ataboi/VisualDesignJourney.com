function __(string $key, ?string $fallback = null): string {
    $lang = vdj_current_language();
    $translations = vdj_translations();
    return $translations[$lang][$key] ?? $fallback ?? $key;
}

function vdj_strip_language_prefix(string $path): string {
    $path = '/' . ltrim($path, '/');
    if (preg_match('#^/(tr|de)(/.*)?$#', $path, $m)) {
        $path = $m[2] ?? '/';
    }
    return $path === '' ? '/' : $path;
}

function vdj_localized_url(string $path, ?string $lang = null): string {
    $lang = $lang ?: vdj_current_language();
    $path = vdj_strip_language_prefix($path);
    $path = '/' . ltrim($path, '/');
    if ($path === '/index.php' || $path === '/explore') $path = '/';

    if ($lang === 'tr' || $lang === 'de') {
        return '/' . $lang . ($path === '/' ? '/' : $path);
    }
    return $path;
}

function vdj_language_url(string $lang): string {
    $uri = $_SERVER['REQUEST_URI'] ?? '/';
    $parts = parse_url($uri);
    $path = vdj_strip_language_prefix($parts['path'] ?? '/');
    parse_str($parts['query'] ?? '', $query);
    if (str_starts_with($path, '/admin')) {
        $query['lang'] = $lang;
        return $path . '?' . http_build_query($query);
    }

    unset($query['lang']);
    $url = vdj_localized_url($path, $lang);
    return $url . ($query ? '?' . http_build_query($query) : '');
}

